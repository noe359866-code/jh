const test = require('node:test');
const assert = require('node:assert/strict');
const { createResolverCache } = require('../engines/sites/cache');
test('deduplicates concurrent requests, expires entries, and returns independent values', async () => {
  let calls = 0;
  let time = 0;
  const resolve = createResolverCache(async () => { calls++; return [{ url: 'https://example.com/a.mp4' }]; }, { ttlMs: 10, now: () => time });
  const [a, b] = await Promise.all([resolve({}), resolve({})]);
  a[0].url = 'modified';
  assert.notEqual(a[0].url, b[0].url);
  assert.equal(calls, 1);
  await resolve({});
  assert.equal(calls, 1);
  time = 11;
  await resolve({});
  assert.equal(calls, 2);
});
test('limits distinct concurrent requests and releases slots after failure', async () => {
  let reject;
  const resolve = createResolverCache(() => new Promise((_, fail) => { reject = fail; }), { maxConcurrent: 1 });
  const pending = resolve({ imdbId: 'a' });
  await assert.rejects(resolve({ imdbId: 'b' }), { code: 'EXTRACTOR_BUSY' });
  reject(new Error('failure'));
  await assert.rejects(pending, /failure/);
  const next = resolve({ imdbId: 'b' });
  await Promise.resolve();
  reject(new Error('next failure'));
  await assert.rejects(next, /next failure/);
});
test('negative results have a shorter TTL and cache size is bounded', async () => {
  let time = 0;
  let calls = 0;
  const resolve = createResolverCache(async () => { calls++; return []; }, { negativeTtlMs: 5, maxEntries: 1, now: () => time });
  await resolve({ imdbId: 'a' });
  await resolve({ imdbId: 'a' });
  assert.equal(calls, 1);
  time = 6;
  await resolve({ imdbId: 'a' });
  await resolve({ imdbId: 'b' });
  await resolve({ imdbId: 'a' });
  assert.equal(calls, 4);
});
